#!/usr/bin/env node
//
// Points .env at one of the per-target env files, so that both `nest start`
// and the Prisma CLI (which reads .env directly and knows nothing about Nest's
// ConfigModule) always agree on which database they are talking to.
//
//   node scripts/use-env.mjs uat     -> .env becomes .env.uat
//   node scripts/use-env.mjs         -> print the active target
//
// Replaces use-env.sh, which could not work on Windows for two reasons: npm
// runs scripts through cmd.exe, which will not execute a .sh at all, and
// git-bash `ln -s` silently COPIES when the account lacks the symlink
// privilege -- so .env became a regular file, the "is it a symlink" check
// failed, and the anti-clobber guard then refused every later switch. That is
// how a hand-edited .env with two DATABASE_URL lines came about.
//
// So: symlink where the OS allows one, and a copy carrying a provenance
// marker where it does not. The marker is what makes the copy as safe as the
// link -- it is how this script tells "a .env I generated, safe to replace"
// from "a .env someone wrote by hand, never clobber", and how it reports the
// active target and notices the copy going stale.

import { existsSync, lstatSync, readFileSync, readlinkSync, rmSync, symlinkSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const envPath = resolve(repoRoot, '.env');

const MARKER = '# generated by scripts/use-env.mjs from';
const markerLine = (target) =>
  `${MARKER} ${target} -- do not edit this file; edit ${target} and re-run \`npm run env:${target.replace(/^\.env\./, '')}\``;

const die = (...lines) => {
  for (const line of lines) console.error(line);
  process.exit(1);
};

/** The target .env was made from: by symlink, or by the marker a copy carries. */
function activeTarget() {
  if (!existsSync(envPath)) return null;
  if (lstatSync(envPath).isSymbolicLink()) return readlinkSync(envPath);
  const first = readFileSync(envPath, 'utf8').split(/\r?\n/, 1)[0];
  return first.startsWith(MARKER) ? first.slice(MARKER.length).trim().split(/\s/)[0] : null;
}

const requested = process.argv[2];

// No argument: report which target is active and stop.
if (!requested) {
  if (!existsSync(envPath)) {
    die("no .env -- run 'npm run env:local' (or :dev / :uat) to pick one");
  }
  const target = activeTarget();
  if (!target) {
    die('active env: .env is a regular file this script did not generate.');
  }
  console.log(`active env: ${target}`);

  // A copy, unlike a link, does not follow later edits to the target. Compare
  // with line endings normalised on both sides: the targets are CRLF here and
  // the marker is written with \n, which would otherwise read as a change.
  const targetPath = resolve(repoRoot, target);
  if (!lstatSync(envPath).isSymbolicLink() && existsSync(targetPath)) {
    const lines = (s) => s.split(/\r?\n/);
    const copied = lines(readFileSync(envPath, 'utf8')).slice(1).join('\n');
    if (copied !== lines(readFileSync(targetPath, 'utf8')).join('\n')) {
      console.error(`warning: ${target} has changed since .env was written from it.`);
      console.error(`         re-run \`npm run env:${target.replace(/^\.env\./, '')}\` to pick the change up.`);
    }
  }
  process.exit(0);
}

const target = `.env.${requested}`;
const targetPath = resolve(repoRoot, target);

if (!existsSync(targetPath)) {
  const { readdirSync } = await import('node:fs');
  const available = readdirSync(repoRoot)
    .filter((f) => f.startsWith('.env.') && !/\.(example|bak.*)$/.test(f))
    .join(' ');
  die(`no such env file: ${target}`, `available: ${available}`);
}

// Refuse to clobber a real .env that was never part of this scheme; losing an
// uncommitted, gitignored file is not recoverable.
if (existsSync(envPath) && !lstatSync(envPath).isSymbolicLink() && !activeTarget()) {
  die(
    '.env is a regular file this script did not generate. Move it aside first:',
    '  mv .env .env.bak-preswitch',
  );
}

if (existsSync(envPath)) rmSync(envPath);

try {
  symlinkSync(target, envPath);
  console.log(`active env: ${target} (symlink)`);
} catch {
  // Windows without the symlink privilege, most often. A marked copy instead.
  writeFileSync(envPath, `${markerLine(target)}\n${readFileSync(targetPath, 'utf8')}`);
  console.log(`active env: ${target} (copy -- this OS would not allow a symlink)`);
}
